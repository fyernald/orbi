// Orbi's own tables. The login tables in auth.ts are generated by Better Auth.

const timestamps = {
	createdAt: timestamp('created_at', { withTimezone: true })
		.defaultNow()
		.notNull(),
	updatedAt: timestamp('updated_at', { withTimezone: true })
		.defaultNow()
		.$onUpdate(() => new Date())
		.notNull(),
};

export const educationLevel = pgEnum('education_level', EDUCATION_LEVELS);

export const profileUse = pgEnum('profile_use', PROFILE_USES);

export const explanationStyle = pgEnum('explanation_style', EXPLANATION_STYLES);

export const studyTime = pgEnum('study_time', STUDY_TIMES);

export const courseColor = pgEnum('course_color', COURSE_COLORS);

// why the student takes the course; the AI tutor can plan around it later
export const courseGoal = pgEnum('course_goal', COURSE_GOALS);

// One row per user, so user_id is the primary key.
export const profile = pgTable('profile', {
	userId: text('user_id')
		.primaryKey()
		.references(() => user.id, { onDelete: 'cascade' }),
	preferredName: varchar('preferred_name', { length: 50 }),
	birthDate: date('birth_date'),
	educationLevel: educationLevel('education_level'),
	institution: text('institution'),
	fieldOfStudy: text('field_of_study'),
	occupation: text('occupation'),
	locale: text('locale'),
	interests: text('interests')
		.array()
		.notNull()
		.default(sql`'{}'::text[]`),
	// IANA name, for example "Europe/Istanbul"
	timezone: text('timezone'),
	uses: profileUse('uses')
		.array()
		.notNull()
		.default(sql`'{}'::profile_use[]`),
	explanationStyle: explanationStyle('explanation_style'),
	dailyMinutes: integer('daily_minutes'),
	studyTime: studyTime('study_time'),
	// the daily study reminder email, sent at reminder_time in the user's time zone
	reminderEnabled: boolean('reminder_enabled').notNull().default(false),
	reminderTime: time('reminder_time'),
	// the catalog id new chats start on; null (or a model the server cannot call
	// any more) means the server's default
	defaultModelId: text('default_model_id'),
	// set once every onboarding question is answered; the app stays closed until then
	onboardedAt: timestamp('onboarded_at', { withTimezone: true }),
	...timestamps,
});

export const course = pgTable(
	'course',
	{
		id: uuid('id').primaryKey().defaultRandom(),
		userId: text('user_id')
			.notNull()
			.references(() => user.id, { onDelete: 'cascade' }),
		name: varchar('name', { length: 255 }).notNull(),
		description: text('description'),
		color: courseColor('color').notNull().default('blue'),
		goal: courseGoal('goal').notNull().default('keep_up'),
		examDate: date('exam_date'),
		...timestamps,
	},
	// also the index for "courses of a user"
	(t) => [unique('course_user_id_id_key').on(t.userId, t.id)]
);

// topic and note keep user_id for simple ownership checks. The foreign keys
// include user_id, so it always matches the owner of the course.
export const topic = pgTable(
	'topic',
	{
		id: uuid('id').primaryKey().defaultRandom(),
		userId: text('user_id').notNull(),
		courseId: uuid('course_id').notNull(),
		name: varchar('name', { length: 255 }).notNull(),
		position: integer('position').notNull().default(0),
		// the student's own day it was ticked off in the study plan
		planDoneOn: date('plan_done_on'),
		...timestamps,
	},
	(t) => [
		foreignKey({
			name: 'topic_course_fk',
			columns: [t.userId, t.courseId],
			foreignColumns: [course.userId, course.id],
		}).onDelete('cascade'),
		unique('topic_user_id_id_key').on(t.userId, t.id),
		index('topic_course_id_idx').on(t.courseId, t.position),
	]
);

export const note = pgTable(
	'note',
	{
		id: uuid('id').primaryKey().defaultRandom(),
		userId: text('user_id').notNull(),
		topicId: uuid('topic_id').notNull(),
		title: varchar('title', { length: 255 }).notNull(),
		content: text('content').notNull(),
		// for a note taken from a PDF: the file's name, and a SHA-256 of its bytes so
		// the same file uploaded again reuses its notes
		sourceName: varchar('source_name', { length: 255 }),
		sourceHash: varchar('source_hash', { length: 64 }),
		...timestamps,
	},
	(t) => [
		foreignKey({
			name: 'note_topic_fk',
			columns: [t.userId, t.topicId],
			foreignColumns: [topic.userId, topic.id],
		}).onDelete('cascade'),
		// the notes list: a topic's notes, newest first
		index('note_topic_created_at_idx').on(t.topicId, t.createdAt.desc()),
		index('note_user_id_idx').on(t.userId),
		index('note_source_hash_idx').on(t.topicId, t.sourceHash),
		// at least one character that is not a space or a line break
		check('note_content_not_empty', sql`${t.content} ~ '\\S'`),
	]
);

export const tutorAction = pgEnum('tutor_action', TUTOR_ACTIONS);

